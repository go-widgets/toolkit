// Package scalesweep discovers, from the toolkit's own source, every exported
// struct type, so the HiDPI sweep (scalesweep_test.go in the toolkit package)
// covers a widget the day it is added instead of the day someone remembers to
// list it.
//
// Discovery reads the source rather than a hand-kept table: a table is exactly
// the thing that silently omits the next widget. Files with a build constraint
// are skipped so the answer is the same on every platform.
package scalesweep

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Type is one exported struct type; Ctor is set when the package has a
// `func NewT() *T` taking nothing, which the sweep prefers to a zero value
// (many widgets are unusable until their constructor ran).
type Type struct {
	Name string
	Ctor bool
}

// Types returns the sorted exported, non-generic struct types declared in the
// non-test, unconstrained .go files of dir.
func Types(dir string) ([]Type, error) {
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	seen := map[string]bool{}
	ctors := map[string]bool{}
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") {
			continue
		}
		src, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		if bytes.Contains(src, []byte("\n//go:build ")) || bytes.HasPrefix(src, []byte("//go:build ")) {
			continue
		}
		af, err := parser.ParseFile(token.NewFileSet(), f, src, 0)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", f, err)
		}
		for _, d := range af.Decls {
			if fd, ok := d.(*ast.FuncDecl); ok && fd.Recv == nil && strings.HasPrefix(fd.Name.Name, "New") &&
				fd.Type.TypeParams == nil && len(fd.Type.Params.List) == 0 &&
				fd.Type.Results != nil && len(fd.Type.Results.List) == 1 {
				if st, ok := fd.Type.Results.List[0].Type.(*ast.StarExpr); ok {
					if id, ok := st.X.(*ast.Ident); ok && id.Name == strings.TrimPrefix(fd.Name.Name, "New") {
						ctors[id.Name] = true
					}
				}
			}
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, s := range gd.Specs {
				ts := s.(*ast.TypeSpec)
				if _, isStruct := ts.Type.(*ast.StructType); isStruct && ts.Name.IsExported() && ts.TypeParams == nil && ts.Assign == token.NoPos {
					seen[ts.Name.Name] = true
				}
			}
		}
	}
	names := make([]Type, 0, len(seen))
	for n := range seen {
		names = append(names, Type{n, ctors[n]})
	}
	sort.Slice(names, func(i, j int) bool { return names[i].Name < names[j].Name })
	return names, nil
}

// Generate is the text of the generated test file listing every type.
func Generate(names []Type) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/scalesweep/gen; DO NOT EDIT.\n\n")
	b.WriteString("package toolkit\n\n")
	b.WriteString("// sweepTypes constructs every exported struct type of the\n")
	b.WriteString("// package (by its no-argument constructor when it has one); the sweep keeps the ones that are widgets.\n")
	b.WriteString("var sweepTypes = []struct {\n\tname string\n\tnew  func() any\n}{\n")
	for _, n := range names {
		if n.Ctor {
			fmt.Fprintf(&b, "\t{%q, func() any { return New%s() }},\n", n.Name, n.Name)
		} else {
			fmt.Fprintf(&b, "\t{%q, func() any { return new(%s) }},\n", n.Name, n.Name)
		}
	}
	b.WriteString("}\n")
	return b.Bytes()
}
