package iconsetgen

import (
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"github.com/go-icons/iconoir"
)

func write(t *testing.T, dir, name, body string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

// fixture is a package whose sources name two icons ("xmark" twice), a non-icon
// string, a number, and whose test file, generated file, non-Go file and
// subdirectory name icons that must NOT be collected.
func fixture(t *testing.T) string {
	dir := t.TempDir()
	write(t, dir, "a.go", "package p\n\nvar a, b, c = \"xmark\", `folder`, \"not-an-icon\"\n")
	write(t, dir, "b.go", "package p\n\nvar d, n = \"xmark\", 42\n")
	write(t, dir, "a_test.go", "package p\n\nvar e = \"airplane\"\n")
	write(t, dir, OutFile, "package p\n\nvar f = \"bold\"\n")
	write(t, dir, "notes.txt", "\"italic\"\n")
	sub := filepath.Join(dir, "sub")
	if err := os.Mkdir(sub, 0o755); err != nil {
		t.Fatal(err)
	}
	write(t, sub, "s.go", "package s\n\nvar g = \"code\"\n")
	return dir
}

func TestNames(t *testing.T) {
	got, err := Names(fixture(t))
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"folder", "xmark"}; !slices.Equal(got, want) {
		t.Fatalf("Names = %q, want %q", got, want)
	}
}

func TestGenerate(t *testing.T) {
	src, err := Generate(fixture(t), "p")
	if err != nil {
		t.Fatal(err)
	}
	s := string(src)
	for _, want := range []string{
		"// Code generated by internal/iconsetgen; DO NOT EDIT.",
		"// Copyright (c) 2021 Luca Burgio",
		"package p\n",
		"const builtinIconCount = 2\n",
		`case "folder":`,
		`case "xmark":`,
	} {
		if !strings.Contains(s, want) {
			t.Errorf("generated source lacks %q", want)
		}
	}
	if strings.Contains(s, `"airplane"`) || strings.Contains(s, `"bold"`) {
		t.Error("generated source holds a name from a test or generated file")
	}
	if !strings.Contains(s, strings.ReplaceAll(iconoir.Icon("xmark")[:20], `"`, `\"`)) {
		t.Error("generated source lacks the xmark SVG")
	}
}

func TestErrors(t *testing.T) {
	missing := filepath.Join(t.TempDir(), "missing")
	if _, err := Names(missing); err == nil {
		t.Error("Names of a missing directory: nil error")
	}
	if _, err := Generate(missing, "p"); err == nil {
		t.Error("Generate of a missing directory: nil error")
	}
	bad := t.TempDir()
	write(t, bad, "x.go", "package p\n\nvar = \n")
	if _, err := Names(bad); err == nil {
		t.Error("Names of an unparsable file: nil error")
	}
}
