// Names returns, sorted and without duplicates, every string literal in the
// non-test Go files of dir (OutFile excluded) that is an Iconoir icon name.
func Names(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	seen := map[string]bool{}
	for _, e := range entries {
		n := e.Name()
		if e.IsDir() || !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") || n == OutFile {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, n), nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		ast.Inspect(f, func(node ast.Node) bool {
			lit, ok := node.(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				return true
			}
			s, err := strconv.Unquote(lit.Value)
			if err == nil && s != "" && iconoir.Has(s) {
				seen[s] = true
			}
			return true
		})
	}
	names := make([]string, 0, len(seen))
	for n := range seen {
		names = append(names, n)
	}
	slices.Sort(names)
	return names, nil
}

// Generate returns the gofmt'd source of OutFile for the package in dir, whose
// package clause is pkg: a builtinIcon(name) switch over the subset Names finds.
func Generate(dir, pkg string) ([]byte, error) {
	names, err := Names(dir)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/iconsetgen; DO NOT EDIT.\n")
	b.WriteString("// Regenerate: go generate (see svgicon.go).\n\n")
	b.WriteString("// The SVG documents below are Iconoir icons (https://iconoir.com), copied\n")
	b.WriteString("// from github.com/go-icons/iconoir, under the following license:\n//\n")
	for _, line := range strings.Split(license, "\n") {
		if line == "" {
			b.WriteString("//\n")
			continue
		}
		b.WriteString("// " + line + "\n")
	}
	fmt.Fprintf(&b, "\npackage %s\n\n", pkg)
	fmt.Fprintf(&b, "// builtinIconCount is the number of Iconoir glyphs the toolkit carries.\n")
	fmt.Fprintf(&b, "const builtinIconCount = %d\n\n", len(names))
	b.WriteString("// builtinIcon returns the SVG document of the named Iconoir glyph, for the\n")
	b.WriteString("// glyphs the toolkit's own widgets draw, or \"\" for any other name.\n")
	b.WriteString("func builtinIcon(name string) string {\n\tswitch name {\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\tcase %s:\n\t\treturn %s\n", strconv.Quote(n), strconv.Quote(iconoir.Icon(n)))
	}
	b.WriteString("\t}\n\treturn \"\"\n}\n")
	return format.Source(b.Bytes())
}
