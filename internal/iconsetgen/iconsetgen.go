// Package iconsetgen writes the toolkit's built-in icon subset: the Iconoir
// SVGs the toolkit's own widgets draw, and no others.
//
// go-icons/iconoir embeds its whole set behind one //go:embed, and the linker
// cannot drop part of an embed.FS, so a package that imports it links about
// 1,500 SVGs into every binary (go-widgets/toolkit#588). The toolkit therefore
// does not import it: this generator copies the glyphs it needs into a Go file,
// and only the toolkit's tests (and this package) depend on the full set.
//
// The subset is derived, not listed: every string literal in the package's
// non-test sources that names an Iconoir icon is kept. That can keep a word
// that is not used as an icon ("text", "page"), which costs a few hundred
// bytes; it cannot drop a name the code draws, because every icon name the
// toolkit passes is a literal somewhere in its source.
package iconsetgen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/go-icons/iconoir"
)

// OutFile is the generated file's name, inside the scanned package directory.
// It is never scanned itself, so a stale subset cannot keep its own names alive.
const OutFile = "iconset_gen.go"

